function t(k, p) {
  let s = I18N[LANG] && ((p && p.n === 1 && I18N[LANG][k + '.1']) || I18N[LANG][k]);
  if (s == null) s = I18N.en[k];
  if (s == null) return k;
  if (p) s = s.replace(/\{(\w+)\}/g, (m, x) => p[x] != null ? p[x] : m);
  return s;
}
