let LANG = 'hu';
function t(k, p) {
  let s = I18N[LANG] && ((p && p.n === 1 && I18N[LANG][k + '.1']) || I18N[LANG][k]);
  if (s == null) s = I18N.en[k];
  if (s == null) return k;
  if (p) s = s.replace(/\{(\w+)\}/g, (m, x) => p[x] != null ? p[x] : m);
  return s;
}
const loc = () => LANG === 'hu' ? 'hu-HU' : 'en-GB';
function initLang() {
  let l = null;
  try { l = localStorage.getItem('boxutca_lang'); } catch (e) { }
  if (!l || !I18N[l]) l = (navigator.language || 'en').toLowerCase().startsWith('hu') ? 'hu' : 'en';
  LANG = l;
}
function setLang(l) {
  if (!I18N[l]) return; LANG = l;
  try { localStorage.setItem('boxutca_lang', l); } catch (e) { }
  render();
}
